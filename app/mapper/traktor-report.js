// Traktor mapping report (FS-32 §5, AC-6): a human-readable Markdown table for entering a mapping by hand in
// Traktor's Controller Manager. Writing .tsi files is out of scope (binary TLV frames in a Base64 attribute, high
// break risk across Traktor versions). The same builder serves the experimental Serato report (serato.js).
// All model text is escaped for Markdown tables (and for HTML, should the report be rendered).

import { FUNCTION_TARGETS, describeFunction } from './vocabulary.js';
import { normalizeModel, cleanText } from './model.js';

/** One Markdown table cell: no line breaks, pipes/backticks/markup escaped. */
export function mdCell(value) {
  return cleanText(value, 200).replace(/[\\`*_[\]|<>&#]/g, c => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c] || `\\${c}`)) || '—';
}

const midiCell = m => (m.type === 'note' ? `Note ${m.number}` : m.type === 'cc14' ? `CC ${m.number}/${m.lsbNumber} (14-bit)` : m.type === 'pitchbend' ? 'Pitch bend' : `CC ${m.number}`) + `, ch ${m.channel}`;

/**
 * Build a report for `target` ('traktor' | 'serato'): heading, status line, how-to steps, then one row per assigned
 * control. Custom/preserved controls from other programs are listed separately by their original names.
 */
export function mappingReport(model, { target, title, status, steps = [] }) {
  const m = normalizeModel(model);
  if (!m) return `# ${title}\n\nThere is no mapping to report.\n`;
  const names = FUNCTION_TARGETS[target];
  const lines = [
    `# ${mdCell(m.name)}: ${title}`,
    '',
    `**${status}.** Generated by DeckChek MIDI mapper studio. ${m.decks} deck${m.decks === 1 ? '' : 's'}.`,
    '',
    ...steps.map((s, i) => `${i + 1}. ${s}`),
    '',
    `| Control | MIDI message | Layer | DeckChek function | Command in ${target === 'traktor' ? 'Traktor' : 'Serato'} | Deck | LED |`,
    '|---|---|---|---|---|---|---|',
  ];
  const assigned = m.controls.filter(c => c.function);
  for (const c of assigned) {
    const fn = c.function;
    lines.push(`| ${mdCell(c.label)} | ${mdCell(midiCell(c.midi))} | ${c.layer === 'shift' ? 'Shift' : 'Base'} | ${mdCell(describeFunction(fn))} | ${mdCell(names[fn.id]?.(fn) || 'No equivalent')} | ${fn.deck ? `Deck ${'ABCD'[fn.deck - 1]} (${fn.deck})` : '—'} | ${c.feedback?.led ? mdCell(`${c.feedback.led.type === 'note' ? 'Note' : 'CC'} ${c.feedback.led.number}, ch ${c.feedback.led.channel}`) : '—'} |`);
  }
  if (!assigned.length) lines.push('| — | — | — | No control has a function yet | — | — | — |');
  const custom = m.controls.filter(c => c.custom);
  if (custom.length) {
    lines.push('', '## Preserved custom controls', '', 'These came from an imported file and have no DeckChek function. Recreate them by hand if you need them.', '', '| Control | MIDI message | Original |', '|---|---|---|');
    for (const c of custom) lines.push(`| ${mdCell(c.label)} | ${mdCell(midiCell(c.midi))} | ${mdCell(c.custom.target === 'mixxx' ? `${c.custom.group} ${c.custom.key}` : `${c.custom.name}: ${c.custom.action}`)} |`);
  }
  const unassigned = m.controls.filter(c => !c.function && !c.custom).length;
  if (unassigned) lines.push('', `${unassigned} control${unassigned === 1 ? ' has' : 's have'} no function and ${unassigned === 1 ? 'is' : 'are'} not listed.`);
  return lines.join('\n') + '\n';
}

/** traktorReport(model) -> Markdown string (FS-32 §4). */
export function traktorReport(model) {
  return mappingReport(model, {
    target: 'traktor', title: 'Traktor mapping report', status: 'Report only: DeckChek does not write Traktor .tsi files',
    steps: [
      'In Traktor open Preferences > Controller Manager and choose Add… > Generic MIDI for your controller (In-Port and Out-Port set to it).',
      'Set the Modifier #1 entry first if the table has a Shift row (Shift layer rows use Modifier #1 = 1 as their condition).',
      'For each row: Add In… > the command listed, then Learn and move the control, or type the MIDI message shown. Set Assignment to the deck shown.',
      'For rows with an LED: Add Out… with the same command and the LED message shown.',
    ],
  });
}
