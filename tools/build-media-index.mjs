// Regenerates app/media/index.json from app/media/profiles/*.json.
// Run: node tools/build-media-index.mjs        (writes the index)
//      node tools/build-media-index.mjs --check (exit 1 when out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MEDIA = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'media');

export function buildIndex(dir = MEDIA) {
  const ids = fs.readdirSync(path.join(dir, 'profiles')).filter(f => f.endsWith('.json')).map(f => f.slice(0, -5)).sort();
  return { schemaVersion: 1, note: 'Generated by tools/build-media-index.mjs; do not edit by hand.', profiles: ids };
}

export const serializeIndex = index => `${JSON.stringify(index, null, 2)}\n`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(MEDIA, 'index.json');
  const next = serializeIndex(buildIndex());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current !== next) { console.error('app/media/index.json is out of date; run node tools/build-media-index.mjs'); process.exit(1); }
    console.log('app/media/index.json is up to date.');
  } else {
    fs.writeFileSync(file, next);
    console.log(`Wrote ${file} (${buildIndex().profiles.length} profiles).`);
  }
}
