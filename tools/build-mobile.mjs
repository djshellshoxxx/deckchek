// DeckChek Mobile build step (FS-30 §4). There is no bundler: this script only
//   1. copies the shared engines from app/ into mobile/vendor/ (flat), byte for byte, and writes vendor/VERSION;
//   2. stamps the service worker's precache list and cache name (the block between the BUILD markers in sw.js)
//      from the hashes of every file in mobile/, so any change to any file invalidates the offline cache.
//   node tools/build-mobile.mjs            write both
//   node tools/build-mobile.mjs --check    exit 1 when a vendored copy or the sw.js stamp is out of date (CI)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Engines shared with the desktop app, relative to app/. Copied unchanged. */
export const SHARED = ['core.js', 'advanced.js', 'calibration.js', 'canonical-json.js', 'sha256.js', 'phone-run.js', 'vendor/qr.js'];
export const VERSION_FILE = 'vendor/VERSION';
const START = '/* BUILD:START (generated by tools/build-mobile.mjs, do not edit) */';
const END = '/* BUILD:END */';
const sha = buf => crypto.createHash('sha256').update(buf).digest('hex');

function listFiles(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full, base));
    else out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

/** Files the service worker precaches: everything in mobile/ except itself and docs. */
export const precacheCandidates = files => files.filter(f => f !== 'sw.js' && !/\.md$/i.test(f));

export function versionText(root = ROOT) {
  const lines = SHARED.map(f => `${sha(fs.readFileSync(path.join(root, 'app', f)))}  ${path.basename(f)}`);
  return `# Copied unchanged from app/ by tools/build-mobile.mjs. Run it again after changing a shared file.\n${lines.join('\n')}\n`;
}

export function swBlock(root = ROOT, versionContent = versionText(root)) {
  const mobile = path.join(root, 'mobile');
  const files = precacheCandidates(listFiles(mobile));
  const hashes = files.map(f => [f, f === VERSION_FILE ? sha(versionContent) : sha(fs.readFileSync(path.join(mobile, f)))]);
  const build = sha(hashes.map(([f, h]) => `${f}:${h}`).join('\n')).slice(0, 12);
  const list = ['./', ...files.filter(f => f !== 'index.html').map(f => `./${f}`), './index.html'];
  return `${START}\nconst BUILD = '${build}';\nconst PRECACHE = ${JSON.stringify(list, null, 2)};\n${END}`;
}

/** Returns the list of problems (check) or the list of files written (write). */
export function buildMobile({ root = ROOT, check = false } = {}) {
  const mobile = path.join(root, 'mobile');
  const changes = [];
  const touch = (rel, content) => {
    const target = path.join(mobile, rel);
    const current = fs.existsSync(target) ? fs.readFileSync(target) : null;
    const same = current && Buffer.compare(current, Buffer.isBuffer(content) ? content : Buffer.from(content)) === 0;
    if (same) return;
    changes.push(rel);
    if (!check) { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
  };
  for (const f of SHARED) touch(`vendor/${path.basename(f)}`, fs.readFileSync(path.join(root, 'app', f)));
  const version = versionText(root);
  touch(VERSION_FILE, version);
  const swPath = path.join(mobile, 'sw.js');
  const sw = fs.readFileSync(swPath, 'utf8');
  const a = sw.indexOf(START), b = sw.indexOf(END);
  if (a < 0 || b < a) throw new Error('mobile/sw.js has no BUILD:START / BUILD:END block');
  // The block depends on file hashes, including sw.js's neighbours that were just (re)written, so compute after the copies.
  const block = swBlock(root, version);
  touch('sw.js', sw.slice(0, a) + block + sw.slice(b + END.length));
  return changes;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changes = buildMobile({ check });
  if (check) {
    if (changes.length) { console.error(`mobile/ is out of date with app/ (${changes.join(', ')}). Run: node tools/build-mobile.mjs`); process.exit(1); }
    console.log('mobile/vendor and the service-worker precache list are up to date');
  } else console.log(changes.length ? `updated: ${changes.join(', ')}` : 'nothing to update');
}
