#!/usr/bin/env node
// Writes THIRD-PARTY-NOTICES.md: the vendored JS code and every Rust crate
// linked into the desktop app (normal and build dependencies of deckchek,
// on the Windows, macOS and Linux targets; dev-only crates are left out).
// Usage: node tools/third-party-notices.mjs [--check]
//   --check  exits 1 when the committed file is out of date or a crate
//            carries a licence outside the reviewed list below.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'THIRD-PARTY-NOTICES.md');
const TARGETS = ['x86_64-pc-windows-msvc', 'aarch64-apple-darwin', 'x86_64-apple-darwin', 'x86_64-unknown-linux-gnu'];
// Licence identifiers reviewed for a proprietary desktop app. MPL-2.0 is weak,
// file-level copyleft: fine to link unmodified, but a change to those files
// must be published. Anything new (GPL, LGPL, AGPL, unknown) fails --check.
const REVIEWED = ['MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', '0BSD', 'Zlib', 'Unlicense', 'CC0-1.0', 'MIT-0',
  'Unicode-3.0', 'Apache-2.0 WITH LLVM-exception', 'MPL-2.0'];

function crates() {
  const all = new Map();
  for (const target of TARGETS) {
    const meta = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--locked', '--filter-platform', target],
      { cwd: path.join(ROOT, 'src-tauri'), maxBuffer: 256 * 1024 * 1024, encoding: 'utf8' }));
    const nodes = new Map(meta.resolve.nodes.map(n => [n.id, n]));
    const pkgs = new Map(meta.packages.map(p => [p.id, p]));
    const seen = new Set();
    const stack = [meta.resolve.root];
    while (stack.length) {
      const id = stack.pop();
      if (seen.has(id)) continue;
      seen.add(id);
      for (const dep of nodes.get(id).deps) {
        if (dep.dep_kinds.some(k => k.kind === null || k.kind === 'build')) stack.push(dep.pkg);
      }
    }
    seen.delete(meta.resolve.root);
    for (const id of seen) {
      const p = pkgs.get(id);
      all.set(`${p.name} ${p.version}`, { name: p.name, version: p.version, license: p.license || `see ${p.license_file || 'crate'}`, repo: p.repository || '' });
    }
  }
  return [...all.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true }));
}

// "MIT/Apache-2.0" is the old SPDX spelling of "MIT OR Apache-2.0".
const terms = license => license.replace(/\//g, ' OR ').split(/\s+(?:OR|AND)\s+/).map(t => t.replace(/[()]/g, '').trim());
const unreviewed = license => terms(license).some(t => !REVIEWED.includes(t));

function render(list) {
  const lines = [
    '# Third-party notices',
    '',
    'DeckChek is proprietary (see LICENSE). It includes or links the third-party components below, each under its own licence.',
    'Generated by `node tools/third-party-notices.mjs` from `src-tauri/Cargo.lock`; do not edit by hand.',
    '',
    '## Vendored source',
    '',
    '| Component | Version | Licence | Where | Source |',
    '|---|---|---|---|---|',
    '| qrcode-generator (Kazuhiko Arase) | 1.4.4 | MIT | `app/vendor/qr.js` (licence text kept in the file header) | https://github.com/kazuhikoarase/qrcode-generator |',
    '',
    'SQLite is compiled into the app through `libsqlite3-sys` (bundled feature). SQLite itself is in the public domain.',
    '',
    '## Licences that need attention',
    '',
    'MPL-2.0 crates are linked unmodified (Tauri pulls them in for HTML/CSS parsing). If DeckChek ever changes one of their files, that file must be published under MPL-2.0.',
    '',
    `## Rust crates linked into the app (${list.length})`,
    '',
    'Normal and build dependencies on Windows, macOS and Linux. Test, fuzz and CI tools are not shipped and are not listed.',
    '',
    '| Crate | Version | Licence | Repository |',
    '|---|---|---|---|',
    ...list.map(c => `| ${c.name} | ${c.version} | ${c.license.replace(/\|/g, '\\|')} | ${c.repo} |`),
    '',
  ];
  return lines.join('\n');
}

const list = crates();
const bad = list.filter(c => unreviewed(c.license));
const text = render(list);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (bad.length) console.error(`Unreviewed licences: ${bad.map(c => `${c.name} ${c.version} (${c.license})`).join(', ')}`);
  if (current !== text) console.error('THIRD-PARTY-NOTICES.md is out of date: run node tools/third-party-notices.mjs');
  process.exit(bad.length || current !== text ? 1 : 0);
}
if (bad.length) console.warn(`Warning: unreviewed licences: ${bad.map(c => `${c.name} ${c.version} (${c.license})`).join(', ')}`);
fs.writeFileSync(OUT, text);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${list.length} crates.`);
