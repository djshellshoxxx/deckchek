// Device test coverage audit (SPEC-34).
// Run: node tools/check-device-coverage.mjs             prints the matrix, exit 1 on any gap
//      node tools/check-device-coverage.mjs --markdown  writes docs/testing/DEVICE-TEST-COVERAGE.md
//      node tools/check-device-coverage.mjs --check     exit 1 when that file is out of date or any gap exists
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { coverageMatrix, capabilitiesOf, REQUIRED_METHOD } from '../app/devices/test-plan.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'app', 'devices', 'profiles');
const OUT = path.join(ROOT, 'docs', 'testing', 'DEVICE-TEST-COVERAGE.md');

export function loadAll(dir = DIR) {
  return fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

export function renderMarkdown(profiles) {
  const rows = coverageMatrix(profiles);
  const mark = (ok, needed) => (!needed ? '–' : ok ? '✓' : '✗');
  const cols = [['physical', 'Inspect'], ['driver', 'Driver'], ['software', 'Software'], ['usbMidi', 'MIDI conf.'], ['midiMap', 'Coverage'], ['midiTiming', 'Timing'], ['audioOut', 'Audio quality'], ['gmSource', 'GM']];
  const lines = ['# Device test coverage', '', 'Generated by `node tools/check-device-coverage.mjs --markdown`; do not edit by hand. Specification: [FS-34](../specs/34-device-test-completeness.md).', '',
    `${rows.length} device profiles. “Hand” = tests written in the profile, “Auto” = baseline tests added by the plan builder for capabilities the profile did not cover (SPEC-34 §4). ✓ covered, ✗ gap, – not applicable.`, '',
    `| Device | Hand | Auto | Total | ${cols.map(c => c[1]).join(' | ')} | Gaps |`, `|---|---:|---:|---:|${cols.map(() => ':-:').join('|')}|---:|`];
  for (const r of rows) {
    const p = profiles.find(x => x.id === r.id);
    const caps = { ...capabilitiesOf(p), midiTiming: capabilitiesOf(p).usbMidi && capabilitiesOf(p).midiMap };
    lines.push(`| ${r.model} | ${r.hand} | ${r.auto} | ${r.total} | ${cols.map(([k]) => mark(r.covered[k], caps[k])).join(' | ')} | ${r.gaps.length} |`);
  }
  const tot = rows.reduce((a, r) => ({ hand: a.hand + r.hand, auto: a.auto + r.auto, gaps: a.gaps + r.gaps.length }), { hand: 0, auto: 0, gaps: 0 });
  lines.push('', `**Totals:** ${tot.hand} hand-written tests, ${tot.auto} auto-added tests, ${tot.gaps} remaining gaps.`, '', '## Required method per capability', '', ...Object.entries(REQUIRED_METHOD).map(([k, v]) => `- ${k}: \`${v}\``), '');
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const profiles = loadAll();
  const rows = coverageMatrix(profiles);
  const gaps = rows.flatMap(r => r.gaps.map(g => `${r.id}: ${g.code} — ${g.message}`));
  const md = renderMarkdown(profiles);
  if (process.argv.includes('--markdown')) { fs.writeFileSync(OUT, md); console.log(`Wrote ${OUT}`); }
  else if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== md) { console.error('docs/testing/DEVICE-TEST-COVERAGE.md is out of date; run node tools/check-device-coverage.mjs --markdown'); process.exit(1); }
  } else for (const r of rows) console.log(`${r.gaps.length ? 'GAP ' : 'ok  '} ${r.id.padEnd(36)} hand ${String(r.hand).padStart(2)} auto ${r.auto} total ${String(r.total).padStart(2)}`);
  if (gaps.length) { console.error(`\n${gaps.length} gap(s):\n${gaps.join('\n')}`); process.exit(1); }
  console.log(`\n${rows.length} devices fully testable.`);
}
